"""Writes lib/ui/schemes.g.dart from the website's design tokens (schemes.css)."""
import re
import sys
from pathlib import Path

css = re.sub(r"/\*.*?\*/", "", Path(sys.argv[1]).read_text(), flags=re.S)
roles = {
    "primary": "primary", "on-primary": "onPrimary", "primary-container": "primaryContainer", "on-primary-container": "onPrimaryContainer",
    "secondary": "secondary", "on-secondary": "onSecondary", "secondary-container": "secondaryContainer", "on-secondary-container": "onSecondaryContainer",
    "tertiary": "tertiary", "on-tertiary": "onTertiary", "tertiary-container": "tertiaryContainer", "on-tertiary-container": "onTertiaryContainer",
    "error": "error", "on-error": "onError", "error-container": "errorContainer", "on-error-container": "onErrorContainer",
    "surface": "surface", "on-surface": "onSurface", "on-surface-variant": "onSurfaceVariant",
    "surface-dim": "surfaceDim", "surface-bright": "surfaceBright",
    "surface-container-lowest": "surfaceContainerLowest", "surface-container-low": "surfaceContainerLow",
    "surface-container": "surfaceContainer", "surface-container-high": "surfaceContainerHigh", "surface-container-highest": "surfaceContainerHighest",
    "outline": "outline", "outline-variant": "outlineVariant", "shadow": "shadow", "scrim": "scrim",
    "inverse-surface": "inverseSurface", "inverse-on-surface": "onInverseSurface", "inverse-primary": "inversePrimary",
    "surface-tint": "surfaceTint",
}
blocks = {}
for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
    sel = selector.strip()
    seed = re.search(r'data-seed="([^"]+)"', sel)
    name = seed.group(1) if seed else "haneoka"
    dark = "dark" in sel
    if not sel.startswith(":root"):
        continue
    values = dict(re.findall(r"--md-sys-color-([a-z-]+):\s*(#[0-9a-fA-F]{6})", body))
    if values:
        blocks.setdefault((name, dark), {}).update(values)

out = ["// Generated by tool/gen_schemes.py from the website's design tokens. Do not edit.", "", "import 'package:flutter/material.dart';", "", "const haneokaSchemes = <String, (ColorScheme, ColorScheme)>{"]
for name in dict.fromkeys(n for n, _ in blocks):
    pair = []
    for dark in (False, True):
        v = blocks.get((name, dark))
        if not v:
            break
        fields = ",\n      ".join(f"{dart}: Color(0xFF{v[css_name][1:].upper()})" for css_name, dart in roles.items() if css_name in v)
        pair.append(f"ColorScheme(\n      brightness: Brightness.{'dark' if dark else 'light'},\n      {fields},\n    )")
    if len(pair) == 2:
        out.append(f"  '{name}': (\n    {pair[0]},\n    {pair[1]},\n  ),")
out.append("};")
# The settings swatches (`--md-ref-band-N`, its container and on-container),
# per brightness: (light, dark) triples of key colour, container and accent.
refs = {}
for selector, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
    if not selector.strip().startswith(":root") or "data-seed" in selector:
        continue
    dark = "dark" in selector
    for band, kind, value in re.findall(r"--md-ref-(band-\d)(-container|-on-container)?:\s*(#[0-9a-fA-F]{6})", body):
        refs.setdefault((band, dark), {})[kind or "key"] = value
out += ["", "/// Theme colour swatches: key, container and on-container, (light, dark).", "const bandSwatches = <String, (List<Color>, List<Color>)>{"]
for band in sorted({b for b, _ in refs}):
    pair = []
    for dark in (False, True):
        v = refs.get((band, dark), {})
        pair.append("[" + ", ".join(f"Color(0xFF{v[k][1:].upper()})" for k in ("key", "-container", "-on-container") if k in v) + "]")
    out.append(f"  '{band}': ({pair[0]}, {pair[1]}),")
out.append("};")
Path(sys.argv[2]).write_text("\n".join(out) + "\n")
print(sorted({n for n, _ in blocks}))
