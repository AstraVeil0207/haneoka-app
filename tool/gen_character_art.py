"""Character portraits from the website's src/config/character-art.ts.

Usage: python3 tool/gen_character_art.py <site-root>
"""
import re, sys
from pathlib import Path

source = (Path(sys.argv[1]) / "src/config/character-art.ts").read_text()
entries = []
for block in re.finditer(r"\n  (\d+): \[(.*?)\n  \],", source, re.S):
    portraits = re.findall(r'source: "([^"]+)"', block.group(2))
    entries.append((block.group(1), portraits))
lines = "\n".join(
    f"  {cid}: [{', '.join(repr(p).replace(chr(34), chr(39)) for p in ps)}],"
    for cid, ps in entries
)
out = Path(__file__).resolve().parent.parent / "lib/catalog/character_art.g.dart"
out.write_text(
    "// Generated by tool/gen_character_art.py from the website's character-art.ts.\n\n"
    "/// Character id → the website's portrait artwork (`CHARACTER_ART`).\n"
    f"const characterArt = <int, List<String>>{{\n{lines}\n}};\n"
)
print(len(entries), "characters")
