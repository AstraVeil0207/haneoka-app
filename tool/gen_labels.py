"""Label paths from the website: catalogue aliases (src/config/catalog-labels.ts),
the catalogue screen's own labels (uiLabelPaths in src/lit/catalog-screen.ts)
and the rotating-system labels (src/i18n/system-labels.ts).

Usage: python3 tool/gen_labels.py <site-root>
"""
import re, sys
from pathlib import Path

root = Path(sys.argv[1])


def entries(text: str) -> dict[str, str]:
    return dict(re.findall(r'"([^"]+)":\s*"([^"]+)"', text))


catalog = (root / "src/config/catalog-labels.ts").read_text()
block = catalog[catalog.index("LABEL_ENTRIES"):catalog.index("const LABEL_ALIASES")]
aliases = dict(re.findall(r'\[\s*"([^"]+)",\s*"([^"]+)"\s*\]', block))

screen = (root / "src/lit/catalog-screen.ts").read_text()
start = screen.index("const uiLabelPaths")
ui = entries(screen[start:screen.index("};", start)])

system_source = (root / "src/i18n/system-labels.ts").read_text()
maps = {}
for name in ("SYSTEM_LABEL_PATHS", "EVENT_LABEL_PATHS"):
    start = system_source.index(f"const {name}")
    maps[name] = entries(system_source[start:system_source.index("};", start)])


def dart(name: str, doc: str, values: dict[str, str]) -> str:
    lines = "\n".join(f"  '{k}': '{v}'," for k, v in values.items())
    return f"/// {doc}\nconst {name} = <String, String>{{\n{lines}\n}};\n"


out = Path(__file__).resolve().parent.parent / "lib/catalog/labels.g.dart"
out.write_text(
    "// Generated by tool/gen_labels.py from the website's label tables.\n\n"
    + dart("catalogLabelPaths", "Catalogue field id → the website's message path (`catalogLabelPath`).", aliases)
    + "\n"
    + dart("uiLabelPaths", "The catalogue screen's alias → message path (`uiLabelPaths`).", ui)
    + "\n"
    + dart("systemLabelPaths", "Rotating-system field ids (`SYSTEM_LABEL_PATHS`).", maps["SYSTEM_LABEL_PATHS"])
    + "\n"
    + dart("eventLabelPaths", "Event field ids (`EVENT_LABEL_PATHS`).", maps["EVENT_LABEL_PATHS"])
)
print(len(aliases), len(ui), {k: len(v) for k, v in maps.items()})
