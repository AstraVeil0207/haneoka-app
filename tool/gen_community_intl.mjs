// Generates lib/community/intl.g.dart from the ICU data the website's
// browser APIs use: region names (Intl.DisplayNames) and relative times
// (Intl.RelativeTimeFormat, numeric: "auto").
import { writeFileSync } from "node:fs";
const locales = ["en", "ja", "ko", "zh-CN", "zh-TW"];
const letters = "ABCDEFGHIJKLMNOPQRSTUVWXYZ";
const units = ["second", "minute", "hour", "day"];
const q = (s) => JSON.stringify(s).replaceAll("$", "\\$");
let out = "// Generated by tool/gen_community_intl.mjs. Do not edit.\n\n";
out += "const regionNames = <String, Map<String, String>>{\n";
for (const locale of locales) {
  const names = new Intl.DisplayNames([locale], { type: "region" });
  out += `  ${q(locale)}: {\n`;
  for (const a of letters) for (const b of letters) {
    const code = a + b;
    let name;
    try { name = names.of(code); } catch { continue; }
    if (name && name !== code) out += `    ${q(code)}: ${q(name)},\n`;
  }
  out += "  },\n";
}
out += "};\n\n";
// Per locale and unit: exact phrases for -1, 0, 1 and templates with {n}
// for each plural category, past and future.
out += "const relativeTimes = <String, Map<String, Map<String, String>>>{\n";
for (const locale of locales) {
  const auto = new Intl.RelativeTimeFormat(locale, { numeric: "auto" });
  const always = new Intl.RelativeTimeFormat(locale, { numeric: "always" });
  const plural = new Intl.PluralRules(locale);
  out += `  ${q(locale)}: {\n`;
  for (const unit of units) {
    out += `    ${q(unit)}: {\n`;
    for (const v of [-2, -1, 0, 1, 2]) out += `      ${q(String(v))}: ${q(auto.format(v, unit))},\n`;
    const samples = { zero: 0, one: 1, two: 2, few: 3, many: 11, other: 5 };
    for (const sign of ["past", "future"]) {
      for (const category of plural.resolvedOptions().pluralCategories) {
        let sample = null;
        for (let n = 2; n < 200; n++) if (plural.select(n) === category) { sample = n; break; }
        if (category === "one") sample = 1;
        if (sample === null) continue;
        const text = always.format(sign === "past" ? -sample : sample, unit);
        out += `      ${q(`${sign}.${category}`)}: ${q(text.replace(new Intl.NumberFormat(locale).format(sample), "{n}"))},\n`;
      }
    }
    out += "    },\n";
  }
  out += "  },\n";
}
out += "};\n";
// zh-TW names the part of the day before a 12-hour time.
const zhTw = new Intl.DateTimeFormat("zh-TW", { dateStyle: "medium", timeStyle: "medium", timeZone: "UTC" });
out += "\nconst zhTwDayPeriods = <String>[\n";
for (let h = 0; h < 24; h++) out += `  ${q(zhTw.formatToParts(Date.UTC(2026, 0, 5, h)).find((p) => p.type === "dayPeriod")?.value ?? "")},\n`;
out += "];\n";
// Intl.ListFormat(locale, { style: "long", type: "conjunction" }) as
// separators: between two, then start / middle / end of longer lists.
out += "\nconst listSeparators = <String, List<String>>{\n";
for (const locale of locales) {
  const f = new Intl.ListFormat(locale, { style: "long", type: "conjunction" });
  const two = f.format(["\u0001", "\u0002"]).split(/[\u0001\u0002]/u)[1];
  const four = f.format(["\u0001", "\u0002", "\u0003", "\u0004"]).split(/[\u0001-\u0004]/u);
  out += `  ${q(locale)}: [${[two, four[1], four[2], four[3]].map(q).join(", ")}],\n`;
}
out += "};\n";
writeFileSync(new URL("../lib/community/intl.g.dart", import.meta.url), out);
// Fixtures for the date format and relative phrases.
const at = Date.UTC(2026, 8, 26, 2, 44, 9);
const fixtures = {};
for (const locale of locales) fixtures[locale] = {
  medium: new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "medium", timeZone: "UTC" }).format(at),
  pm: new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "medium", timeZone: "UTC" }).format(at + 12 * 3600e3 + 3600e3 * 2),
  hours: Array.from({ length: 24 }, (_, h) => new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "medium", timeZone: "UTC" }).format(Date.UTC(2026, 0, 5, h, 7, 3))),
  rel: [-3, -1, 0, 1, 2, 21].flatMap((v) => units.map((u) => [v, u, new Intl.RelativeTimeFormat(locale, { numeric: "auto" }).format(v, u)])),
};
writeFileSync(new URL("../test/fixtures/community_intl.json", import.meta.url), JSON.stringify(fixtures, null, 1));
